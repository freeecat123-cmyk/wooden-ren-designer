const {chromium,devices}=require('playwright');
const fs=require('node:fs');
const out='C:/Users/freee/Documents/自動縱切靠版製作/chair_cad';
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/zh-TW/app');
 await page.waitForLoadState('domcontentloaded');
 const catalog=await page.locator('body').innerText();
 for(const name of ['六柱圈椅','方凳','木工工作桌','餐椅'])if(!catalog.includes(name))throw Error('Missing catalog '+name);
 await page.goto('http://localhost:3000/zh-TW/design/six-slat-chair');
 await page.waitForSelector('canvas');
 await page.locator('input[name=length]:visible').first().fill('560');
 await page.locator('input[name=length]:visible').first().blur();
 await page.waitForURL(u=>u.searchParams.get('length')==='560');
 await page.waitForSelector('[data-cad-outline]');
 const text=await page.locator('body').innerText();
 for(const label of ['工程三視圖','零件圖','材料單','裁切計算器','產生報價','列印 / PDF'])if(!text.includes(label))throw Error('Missing native feature '+label);
 const links=await page.locator('a').evaluateAll(as=>as.map(a=>({text:a.textContent,href:a.getAttribute('href')})).filter(a=>/quote|cut-plan|print/.test(a.href||'')));
 await page.screenshot({path:out+'/native-integrated.png',fullPage:false});
 const canvas=page.locator('canvas').first();await canvas.screenshot({path:out+'/native-chair-thumb.png'});
 const mobile=await browser.newContext({...devices['iPhone 13']});
 const mp=await mobile.newPage();mp.on('pageerror',e=>errors.push(e.message));
 await mp.goto('http://localhost:3000/zh-TW/design/six-slat-chair');await mp.waitForSelector('canvas:visible');
 const sizeButton=mp.getByRole('button',{name:'544mm',exact:true});
 await sizeButton.scrollIntoViewIfNeeded();
 const unobstructed=await sizeButton.evaluate(el=>{const r=el.getBoundingClientRect();return el.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2));});
 if(!unobstructed)throw Error('Mobile size button is covered');
 await sizeButton.click();
 await mp.locator('input[type=number]:visible').first().fill('550');
 await mp.locator('input[type=number]:visible').first().press('Enter');
 await mp.waitForURL(u=>u.searchParams.get('length')==='550');
 await mp.getByRole('button',{name:/進階設定/}).click();
 await mp.locator('input[name=chairLumbar]:visible').fill('25');
 await mp.locator('input[name=chairLumbar]:visible').blur();
 await mp.waitForURL(u=>u.searchParams.get('chairLumbar')==='25');
 await mp.screenshot({path:out+'/native-mobile.png',fullPage:false});
 const mobileText=(await mp.locator('body').innerText()).slice(0,1700);
 fs.writeFileSync(out+'/native-browser-validation.json',JSON.stringify({catalog:true,desktopUrl:page.url(),nativeLinks:links,outlineCount:await page.locator('[data-cad-outline]').count(),mobileText,mobileOverflow:await mp.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors},null,2));
 console.log(JSON.stringify({desktopUrl:page.url(),mobileUrl:mp.url(),unobstructed,links,mobileText,errors}));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
